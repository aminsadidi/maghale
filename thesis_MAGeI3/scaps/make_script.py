"""Generate MAGeI3_all_steps.script - runs the whole Chapter-4 study inside
SCAPS-1D (syntax taken from the example scripts shipped with SCAPS 3.3).
Outputs are written to the SCAPS 'results' folder with the prefix MG_.

Layer numbers in the .def files (left = back contact):
  no buffer : 1 Spiro | 2 MAGeI3 | 3 TiO2 | 4 ITO
  buffer    : 1 Spiro | 2 buffer | 3 MAGeI3 | 4 TiO2 | 5 ITO
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
D_ABS, D_ETL, D_HTL = 0.8, 0.05, 0.05      # um, optimum of steps 1-3
D_BUF = {"WOx": 0.05, "NiOx": 0.05, "V2O5": 0.01}
DEF = {"none": "02_noBuffer_reference.def", "WOx": "03_WOx_buffer_10nm.def",
       "NiOx": "04_NiOx_buffer_10nm.def", "V2O5": "05_V2O5_buffer_10nm.def"}

L = []
a = L.append


def iv(inc=0.02):
    a("clear actions")
    a("action light")
    a("action workingpoint.temperature 300")
    a("action iv.doiv")
    a("action iv.startv 0")
    a("action iv.stopv 1.6")
    a(f"action iv.increment {inc}")
    a("action iv.stopaftervoc 1")


def load(struct, d_abs=D_ABS, d_etl=D_ETL, d_htl=D_HTL, d_buf=None):
    a(f"load definitionfile {DEF[struct]}")
    if struct == "none":
        a(f"set layer1.thickness {d_htl}")
        a(f"set layer2.thickness {d_abs}")
        a(f"set layer3.thickness {d_etl}")
    else:
        a(f"set layer1.thickness {d_htl}")
        a(f"set layer2.thickness {d_buf if d_buf is not None else D_BUF[struct]}")
        a(f"set layer3.thickness {d_abs}")
        a(f"set layer4.thickness {d_etl}")


def run(name):
    a("calculate singleshot")
    a(f"save results.iv MG_{name}.iv")


a("// MAGeI3 thesis - complete Chapter-4 simulation campaign in SCAPS-1D")
a("// generated by make_script.py ; outputs: SCAPS results folder, files MG_*.iv / *.qe / *.cv")
a("set errorhandling.overwritefile")
a("clear all")

# ---------------- Step 1: absorber 100..800 nm (TiO2 100, Spiro 100)
a("// ===== STEP 1: MAGeI3 thickness")
iv()
for d in range(100, 900, 100):
    load("none", d_abs=d / 1000, d_etl=0.1, d_htl=0.1)
    run(f"S1_abs{d:03d}")
# ---------------- Step 2: TiO2 1..400 nm
a("// ===== STEP 2: TiO2 thickness")
for d in [1, 50, 100, 150, 200, 250, 300, 350, 400]:
    load("none", d_etl=d / 1000, d_htl=0.1)
    run(f"S2_etl{d:03d}")
# ---------------- Step 3: Spiro 1..200 nm
a("// ===== STEP 3: Spiro-OMeTAD thickness")
for d in [1, 50, 100, 150, 200]:
    load("none", d_htl=d / 1000)
    run(f"S3_htl{d:03d}")
# ---------------- Step 4: buffer thickness
a("// ===== STEP 4: buffer thickness")
for b in ("WOx", "NiOx", "V2O5"):
    for d in (10, 20, 30, 40, 50):
        load(b, d_buf=d / 1000)
        run(f"S4_{b}_{d:02d}")
# ---------------- Steps 5-6: optimum structures, fine J-V
a("// ===== STEPS 5-6: optimum structures")
iv(0.01)
for s in ("none", "WOx", "NiOx", "V2O5"):
    load(s)
    run(f"S56_{s}")
# ---------------- temperature
a("// ===== temperature 280-360 K")
for s in ("none", "WOx", "NiOx", "V2O5"):
    for T in (280, 300, 320, 340, 360):
        iv()
        a(f"action workingpoint.temperature {T}")
        load(s)
        run(f"T_{s}_{T}")
a("action workingpoint.temperature 300")
# ---------------- absorber defect density
a("// ===== absorber bulk defect density")
iv()
for s, layer in (("none", 2), ("NiOx", 3)):
    for e in (14, 15, 16, 17, 18):
        load(s)
        a(f"set layer{layer}.defect1.ntotal 1E{e}")
        run(f"Nt_{s}_1E{e}")
# ---------------- V2O5 valence-band offset (electron affinity sweep)
a("// ===== V2O5 band offset (chi sweep)")
for chi in (1.2, 1.4, 1.6, 1.7, 1.8, 1.9, 2.0, 2.1, 2.3):
    load("V2O5")
    a(f"set layer2.chi {chi}")
    run(f"VBO_chi{int(round(chi * 100)):03d}")
# ---------------- Step 7: QE
a("// ===== STEP 7: IPCE / QE")
for s in ("none", "WOx", "NiOx", "V2O5"):
    a("clear actions")
    a("action light")
    a("action qe.doqe")
    a("action qe.startlambda 300")
    a("action qe.stoplambda 900")
    a("action qe.increment 10")
    load(s)
    a("calculate singleshot")
    a(f"save results.qe MG_QE_{s}.qe")
# ---------------- C-V (dark, 1 kHz)
a("// ===== C-V, Mott-Schottky (dark, 1 kHz)")
for s in ("none", "WOx", "NiOx", "V2O5"):
    a("clear actions")
    a("action dark")
    a("action workingpoint.frequency 1000")
    a("action cv.docv")
    a("action cv.startv -0.4")
    a("action cv.stopv 1.2")
    a("action cv.increment 0.05")
    load(s)
    a("calculate singleshot")
    a(f"save results.cv MG_CV_{s}.cv")
a("action workingpoint.frequency 1000000")
# ---------------- energy bands at short circuit (last: least certain command)
a("// ===== energy bands at V = 0 under light")
for s in ("none", "WOx", "NiOx", "V2O5"):
    a("clear actions")
    a("action light")
    a("action iv.doiv")
    a("action iv.startv 0")
    a("action iv.stopv 0")
    a("action iv.points 2")
    load(s)
    a("calculate singleshot")
    a(f"save results.eb MG_EB_{s}.eb")
a("// ===== finished")

if __name__ == "__main__":
    out = os.path.join(HERE, "def", "MAGeI3_all_steps.script")
    with open(out, "w", newline="", encoding="ascii") as fh:
        fh.write("\r\n".join(L) + "\r\n")
    print("wrote", out, len(L), "lines")
