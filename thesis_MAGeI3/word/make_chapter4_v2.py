def sci(v):
    if v != 0 and 1e-2 <= abs(v) < 1e3:
        return f"{v:g}"
    return "0" if v == 0 else f"{v:.2e}".replace("e+0", "E+").replace("e-0", "E-").replace("e+", "E+").replace("e-", "E-")


