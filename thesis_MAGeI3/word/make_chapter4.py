def ser(rows, struct, xkey, ykey):
    return [(r[xkey], r[ykey]) for r in rows if r["structure"] == struct]


def tval(struct, T, key):
    for r in TEMP:
        if r["structure"] == struct and int(r["T_K"]) == T:
            return r[key]


def slope(struct, key):
    T = [r["T_K"] for r in TEMP if r["structure"] == struct]
    y = [r[key] for r in TEMP if r["structure"] == struct]
    return np.polyfit(T, y, 1)[0]


def nit(struct, N, key):
    for r in NIT:
        if r["structure"] == struct and abs(np.log10(r["Nit_cm2"]) - np.log10(N)) < 0.01:
            return r[key]


def nt(struct, N, key):
    for r in NT:
        if r["structure"] == struct and abs(np.log10(r["Nt_cm3"]) - np.log10(N)) < 0.01:
            return r[key]


def eqe_at(struct, lam):
    for r in EQE:
        if abs(r["lambda_nm"] - lam) < 1e-6:
            return r[f"EQE_{struct}"]


def jint(struct):
    return EQE[-1][f"Jint_{struct}"]


def zinfo(struct):
    f = np.array([r["f_Hz"] for r in ZN]); zr = np.array([r[f"Zre_{struct}"] for r in ZN])
    zi = np.array([r[f"Zim_{struct}"] for r in ZN])
    i = int(np.argmax(-zi))
    Rrec = zr[0] - zr[-1]
    return dict(Rlow=zr[0], Rs=zr[-1], fpk=f[i], tau=1 / (2 * np.pi * f[i]), C=1 / (2 * np.pi * f[i] * Rrec))


def pct(a, b):
    return 100 * (a - b) / b


def ffa(x):
    """scientific notation in Persian text: 1e+16 -> 10^{16}"""
    e = int(np.round(np.log10(x)))
    m = x / 10 ** e
    return f"10^{{{e}}}" if abs(m - 1) < 1e-6 else f"{m:.1f}×10^{{{e}}}"


